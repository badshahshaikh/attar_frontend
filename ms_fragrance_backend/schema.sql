CREATE TABLE IF NOT EXISTS products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    category TEXT DEFAULT 'Attar',
    fragrance_type TEXT,
    description TEXT,
    full_description TEXT,
    rating NUMERIC DEFAULT 0,
    reviews INTEGER DEFAULT 0,
    price NUMERIC NOT NULL,
    original_price NUMERIC,
    size_pricing JSONB NOT NULL DEFAULT '{}'::jsonb,
    sizes JSONB NOT NULL DEFAULT '[]'::jsonb,
    top_notes JSONB NOT NULL DEFAULT '[]'::jsonb,
    heart_notes JSONB NOT NULL DEFAULT '[]'::jsonb,
    base_notes JSONB NOT NULL DEFAULT '[]'::jsonb,
    longevity TEXT,
    in_stock BOOLEAN NOT NULL DEFAULT TRUE,
    is_new BOOLEAN NOT NULL DEFAULT FALSE,
    brand TEXT,
    is_best_seller BOOLEAN NOT NULL DEFAULT FALSE,
    is_exclusive BOOLEAN NOT NULL DEFAULT FALSE,
    featured BOOLEAN NOT NULL DEFAULT FALSE,
    stock_quantity INTEGER NOT NULL DEFAULT 0,
    slug TEXT,
    image_url TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS products_brand_idx ON products (brand);
CREATE INDEX IF NOT EXISTS products_fragrance_type_idx ON products (fragrance_type);

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_attribute
        WHERE attrelid = 'products'::regclass
          AND attname = 'id'
          AND attidentity <> ''
    ) THEN
        ALTER TABLE products ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
    END IF;
END
$$;

SELECT setval(
    pg_get_serial_sequence('products', 'id'),
    COALESCE((SELECT MAX(id) FROM products), 1),
    (SELECT COUNT(*) > 0 FROM products)
);

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(100) NOT NULL UNIQUE,
    email VARCHAR(255) UNIQUE,
    password_hash TEXT NOT NULL,
    role VARCHAR(50) NOT NULL DEFAULT 'admin',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);