-- ── Customer accounts ────────────────────────────────────────────────────────

-- Saved shipping addresses. At most one address per user may be the default.
CREATE TABLE IF NOT EXISTS addresses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    label VARCHAR(50),
    full_name TEXT NOT NULL,
    phone VARCHAR(20) NOT NULL,
    line1 TEXT NOT NULL,
    line2 TEXT,
    city TEXT NOT NULL,
    state TEXT NOT NULL,
    postal_code VARCHAR(10) NOT NULL,
    country VARCHAR(50) NOT NULL DEFAULT 'India',
    is_default BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS addresses_user_idx ON addresses (user_id);
CREATE UNIQUE INDEX IF NOT EXISTS addresses_one_default ON addresses (user_id) WHERE is_default;

-- Orders. `user_id` is nullable so history survives account deletion, and
-- `shipping_address` is a JSONB snapshot so it is unaffected by later edits.
CREATE TABLE IF NOT EXISTS orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number VARCHAR(32) NOT NULL UNIQUE,
    user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'placed',
    subtotal NUMERIC(12, 2) NOT NULL DEFAULT 0,
    shipping NUMERIC(12, 2) NOT NULL DEFAULT 0,
    total NUMERIC(12, 2) NOT NULL DEFAULT 0,
    contact_name TEXT NOT NULL,
    contact_phone VARCHAR(20) NOT NULL,
    shipping_address JSONB NOT NULL,
    notes TEXT,
    source VARCHAR(20) NOT NULL DEFAULT 'whatsapp',
    payment_status VARCHAR(20) NOT NULL DEFAULT 'unpaid',
    razorpay_order_id TEXT,
    razorpay_payment_id TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS orders_user_idx ON orders (user_id, created_at DESC);

-- Line items snapshot the product name and price so historical orders stay
-- correct even if the product is renamed, repriced or deleted.
CREATE TABLE IF NOT EXISTS order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    product_id BIGINT REFERENCES products(id) ON DELETE SET NULL,
    product_name TEXT NOT NULL,
    size VARCHAR(20),
    quantity INTEGER NOT NULL DEFAULT 1 CHECK (quantity > 0),
    unit_price NUMERIC(12, 2) NOT NULL,
    line_total NUMERIC(12, 2) NOT NULL
);

CREATE INDEX IF NOT EXISTS order_items_order_idx ON order_items (order_id);

-- Server-side cart for signed-in customers. Guests keep using localStorage and
-- merge into these tables when they log in.
CREATE TABLE IF NOT EXISTS customer_cart_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    size VARCHAR(20) NOT NULL,
    quantity INTEGER NOT NULL DEFAULT 1 CHECK (quantity > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (user_id, product_id, size)
);

CREATE TABLE IF NOT EXISTS customer_wishlist (
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (user_id, product_id)
);

-- ── Admin-managed returns ────────────────────────────────────────────────
-- Delivery timestamp used for the 7-day return window. Stamped when an order
-- is marked delivered; missing on older orders (eligibility then fails closed).
ALTER TABLE public.orders ADD COLUMN IF NOT EXISTS delivered_at TIMESTAMPTZ;

-- One return per customer request against an order.
CREATE TABLE IF NOT EXISTS returns (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    return_number VARCHAR(32) NOT NULL UNIQUE,
    order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    status VARCHAR(30) NOT NULL DEFAULT 'requested',
    customer_reason TEXT NOT NULL,
    internal_notes TEXT,
    unopened_confirmed BOOLEAN NOT NULL DEFAULT FALSE,
    inspected_at TIMESTAMPTZ,
    delivered_at_snapshot TIMESTAMPTZ,
    days_after_delivery INTEGER,
    created_by_admin_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_by_admin_name TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT returns_status_check CHECK (
        status IN ('requested', 'approved', 'rejected', 'pickup_pending',
                   'received', 'refund_pending', 'refunded', 'closed')
    )
);

CREATE INDEX IF NOT EXISTS returns_order_idx ON returns (order_id);
CREATE INDEX IF NOT EXISTS returns_status_idx ON returns (status);

-- Line items of a return. Price/name are snapshots so a later product edit
-- never rewrites what was refunded. A return may contain each order item at
-- most once; across returns the cumulative quantity is capped server-side.
CREATE TABLE IF NOT EXISTS return_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    return_id BIGINT NOT NULL REFERENCES returns(id) ON DELETE CASCADE,
    order_item_id BIGINT NOT NULL REFERENCES order_items(id) ON DELETE RESTRICT,
    product_id BIGINT REFERENCES products(id) ON DELETE SET NULL,
    product_name TEXT NOT NULL,
    size VARCHAR(20),
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(12, 2) NOT NULL,
    line_total NUMERIC(12, 2) NOT NULL,
    stock_restored BOOLEAN NOT NULL DEFAULT FALSE,
    restored_at TIMESTAMPTZ,
    UNIQUE (return_id, order_item_id)
);

CREATE INDEX IF NOT EXISTS return_items_return_idx ON return_items (return_id);
CREATE INDEX IF NOT EXISTS return_items_order_item_idx ON return_items (order_item_id);

-- Append-only status audit trail. Every transition (including creation) writes
-- a row with the acting admin and an optional note (required for rejections).
CREATE TABLE IF NOT EXISTS return_status_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    return_id BIGINT NOT NULL REFERENCES returns(id) ON DELETE CASCADE,
    from_status VARCHAR(30),
    to_status VARCHAR(30) NOT NULL,
    changed_by_admin_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    changed_by_admin_name TEXT,
    note TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS return_status_history_return_idx
    ON return_status_history (return_id, created_at);

-- Manual refunds. Exactly one row per return (UNIQUE) so a refund can never be
-- recorded twice. Kept separate from orders.payment_status by design — the
-- order keeps its original paid/unpaid state forever.
CREATE TABLE IF NOT EXISTS return_refunds (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    return_id BIGINT NOT NULL UNIQUE REFERENCES returns(id) ON DELETE CASCADE,
    amount NUMERIC(12, 2) NOT NULL CHECK (amount > 0),
    refunded_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    method VARCHAR(30) NOT NULL DEFAULT 'manual',
    reference TEXT,
    recorded_by_admin_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    recorded_by_admin_name TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT return_refunds_method_check CHECK (
        method IN ('manual', 'upi', 'bank_transfer', 'cash', 'other')
    )
);

-- Page-level SEO settings for the storefront.
-- One row per public route (e.g. '/', '/shop', '/product/42').
-- product_id links product pages to their product for default derivation.
CREATE TABLE IF NOT EXISTS seo_settings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    page_type VARCHAR(50) NOT NULL,
    route_path TEXT NOT NULL UNIQUE,
    seo_title TEXT,
    meta_description TEXT,
    canonical_url TEXT,
    robots TEXT NOT NULL DEFAULT 'index,follow',
    og_title TEXT,
    og_description TEXT,
    og_image TEXT,
    twitter_card TEXT NOT NULL DEFAULT 'summary_large_image',
    twitter_title TEXT,
    twitter_description TEXT,
    twitter_image TEXT,
    structured_data JSONB NOT NULL DEFAULT '{}'::jsonb,
    product_id BIGINT REFERENCES products(id) ON DELETE SET NULL,
    is_published BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS seo_settings_route_idx ON seo_settings (route_path);
CREATE INDEX IF NOT EXISTS seo_settings_product_idx ON seo_settings (product_id);
CREATE INDEX IF NOT EXISTS seo_settings_page_type_idx ON seo_settings (page_type);

-- Constraint: page_type must be a recognized public page type.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'seo_settings_page_type_check'
    ) THEN
        ALTER TABLE seo_settings
            ADD CONSTRAINT seo_settings_page_type_check
            CHECK (page_type IN ('homepage', 'shop', 'category', 'product'));
    END IF;
END
$$;

-- Constraint: robots must contain only safe, known directives.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'seo_settings_robots_check'
    ) THEN
        ALTER TABLE seo_settings
            ADD CONSTRAINT seo_settings_robots_check
            CHECK (robots ~* '^(index|noindex),(follow|nofollow)$');
    END IF;
END
$$;