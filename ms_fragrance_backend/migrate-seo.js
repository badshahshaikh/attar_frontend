/**
 * migrate-seo.js
 *
 * Schema migration for page-level SEO settings.
 *
 * Mirrors the new `seo_settings` section in schema.sql. Every statement is
 * idempotent, so this script is safe to re-run on existing databases.
 *
 * Usage: node migrate-seo.js  (or: npm run migrate:seo)
 */
import { query, closeDb } from './src/infrastructure/database/postgres-database.js';

const STATEMENTS = [
    `CREATE TABLE IF NOT EXISTS seo_settings (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        page_type VARCHAR(50) NOT NULL,
        route_path TEXT NOT NULL UNIQUE,
        seo_title TEXT,
        meta_description TEXT,
        canonical_url TEXT,
        robots TEXT NOT NULL DEFAULT 'index,follow',
        og_title TEXT,
        og_description TEXT,
        og_image TEXT,
        twitter_card TEXT NOT NULL DEFAULT 'summary_large_image',
        twitter_title TEXT,
        twitter_description TEXT,
        twitter_image TEXT,
        structured_data JSONB NOT NULL DEFAULT '{}'::jsonb,
        product_id BIGINT REFERENCES products(id) ON DELETE SET NULL,
        is_published BOOLEAN NOT NULL DEFAULT TRUE,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
        updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    )`,
    'CREATE INDEX IF NOT EXISTS seo_settings_route_idx ON seo_settings (route_path)',
    'CREATE INDEX IF NOT EXISTS seo_settings_product_idx ON seo_settings (product_id)',
    'CREATE INDEX IF NOT EXISTS seo_settings_page_type_idx ON seo_settings (page_type)',
    `DO $$
        BEGIN
            IF NOT EXISTS (
                SELECT 1 FROM pg_constraint WHERE conname = 'seo_settings_page_type_check'
            ) THEN
                ALTER TABLE seo_settings
                    ADD CONSTRAINT seo_settings_page_type_check
                    CHECK (page_type IN ('homepage', 'shop', 'category', 'product'));
            END IF;
        END
    $$`,
    `DO $$
        BEGIN
            IF NOT EXISTS (
                SELECT 1 FROM pg_constraint WHERE conname = 'seo_settings_robots_check'
            ) THEN
                ALTER TABLE seo_settings
                    ADD CONSTRAINT seo_settings_robots_check
                    CHECK (robots ~* '^(index|noindex),(follow|nofollow)$');
            END IF;
        END
    $$`,
];

async function migrate() {
    for (const ddl of STATEMENTS) {
        await query(ddl);
    }
    console.log(`seo_settings schema statements applied: ${STATEMENTS.length}`);

    const present = await query(
        `SELECT table_name FROM information_schema.tables
          WHERE table_schema = 'public'
            AND table_name = 'seo_settings'
          ORDER BY table_name`
    );
    console.log('seo_settings table present:', present.rows.length > 0 ? 'yes' : 'no');

    await closeDb();
}

migrate().catch(async (error) => {
    console.error(`SEO schema migration failed: ${error.message}`);
    try { await closeDb(); } catch { /* already closed */ }
    process.exitCode = 1;
});
