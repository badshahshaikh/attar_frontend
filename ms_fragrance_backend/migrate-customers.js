/**
 * migrate-customers.js
 *
 * Phase 1 schema migration: customer accounts, saved addresses, orders and
 * server-side cart / wishlist.
 *
 * Mirrors schema.sql, which is no longer applied automatically at boot.
 * Every statement is idempotent, so this script is safe to re-run.
 *
 * Usage: node migrate-customers.js
 */
import { query, closeDb } from './src/infrastructure/database/postgres-database.js';

const TABLES = {
    addresses: `
        CREATE TABLE IF NOT EXISTS addresses (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
            label VARCHAR(50),
            full_name TEXT NOT NULL,
            phone VARCHAR(20) NOT NULL,
            line1 TEXT NOT NULL,
            line2 TEXT,
            city TEXT NOT NULL,
            state TEXT NOT NULL,
            postal_code VARCHAR(10) NOT NULL,
            country VARCHAR(50) NOT NULL DEFAULT 'India',
            is_default BOOLEAN NOT NULL DEFAULT FALSE,
            created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
            updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
        )
    `,
    orders: `
        CREATE TABLE IF NOT EXISTS orders (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            order_number VARCHAR(32) NOT NULL UNIQUE,
            user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
            status VARCHAR(30) NOT NULL DEFAULT 'placed',
            subtotal NUMERIC(12, 2) NOT NULL DEFAULT 0,
            shipping NUMERIC(12, 2) NOT NULL DEFAULT 0,
            total NUMERIC(12, 2) NOT NULL DEFAULT 0,
            contact_name TEXT NOT NULL,
            contact_phone VARCHAR(20) NOT NULL,
            shipping_address JSONB NOT NULL,
            notes TEXT,
            source VARCHAR(20) NOT NULL DEFAULT 'whatsapp',
            payment_status VARCHAR(20) NOT NULL DEFAULT 'unpaid',
            razorpay_order_id TEXT,
            razorpay_payment_id TEXT,
            created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
            updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
        )
    `,
    order_items: `
        CREATE TABLE IF NOT EXISTS order_items (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
            product_id BIGINT REFERENCES products(id) ON DELETE SET NULL,
            product_name TEXT NOT NULL,
            size VARCHAR(20),
            quantity INTEGER NOT NULL DEFAULT 1 CHECK (quantity > 0),
            unit_price NUMERIC(12, 2) NOT NULL,
            line_total NUMERIC(12, 2) NOT NULL
        )
    `,
    customer_cart_items: `
        CREATE TABLE IF NOT EXISTS customer_cart_items (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
            product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
            size VARCHAR(20) NOT NULL,
            quantity INTEGER NOT NULL DEFAULT 1 CHECK (quantity > 0),
            created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
            updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
            UNIQUE (user_id, product_id, size)
        )
    `,
    customer_wishlist: `
        CREATE TABLE IF NOT EXISTS customer_wishlist (
            user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
            product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
            created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
            PRIMARY KEY (user_id, product_id)
        )
    `,
};

const INDEXES = [
    'CREATE UNIQUE INDEX IF NOT EXISTS users_email_lower_uniq ON public.users (LOWER(email)) WHERE email IS NOT NULL',
    'CREATE INDEX IF NOT EXISTS users_role_idx ON public.users (role)',
    'CREATE INDEX IF NOT EXISTS addresses_user_idx ON public.addresses (user_id)',
    'CREATE UNIQUE INDEX IF NOT EXISTS addresses_one_default ON public.addresses (user_id) WHERE is_default',
    'CREATE INDEX IF NOT EXISTS orders_user_idx ON public.orders (user_id, created_at DESC)',
    'CREATE INDEX IF NOT EXISTS order_items_order_idx ON public.order_items (order_id)',
];

async function assertNoDuplicateEmails() {
    const duplicates = await query(
        `SELECT LOWER(email) AS email_key, COUNT(*)::int AS count
         FROM public.users
         WHERE email IS NOT NULL
         GROUP BY LOWER(email)
         HAVING COUNT(*) > 1`
    );

    if (duplicates.rows.length > 0) {
        throw new Error(
            `Duplicate emails (case-insensitive) block users_email_lower_uniq: ${JSON.stringify(duplicates.rows)}`
        );
    }
}

async function migrate() {
    // Guard first: the case-insensitive unique index cannot be built over
    // duplicates, and failing here is clearer than a raw Postgres error.
    await assertNoDuplicateEmails();

    // Accounts: customers register with email only, so username becomes optional.
    await query('ALTER TABLE public.users ALTER COLUMN username DROP NOT NULL');
    await query("ALTER TABLE public.users ALTER COLUMN role SET DEFAULT 'customer'");
    await query('ALTER TABLE public.users ADD COLUMN IF NOT EXISTS full_name TEXT');
    await query('ALTER TABLE public.users ADD COLUMN IF NOT EXISTS phone VARCHAR(20)');
    await query('ALTER TABLE public.users ADD COLUMN IF NOT EXISTS last_login_at TIMESTAMPTZ');

    // Online payments (Razorpay): safe to re-run on an existing orders table.
    await query("ALTER TABLE public.orders ADD COLUMN IF NOT EXISTS payment_status VARCHAR(20) NOT NULL DEFAULT 'unpaid'");
    await query('ALTER TABLE public.orders ADD COLUMN IF NOT EXISTS razorpay_order_id TEXT');
    await query('ALTER TABLE public.orders ADD COLUMN IF NOT EXISTS razorpay_payment_id TEXT');

    for (const [name, ddl] of Object.entries(TABLES)) {
        await query(ddl);
        console.log(`table ready: ${name}`);
    }

    for (const ddl of INDEXES) {
        await query(ddl);
    }
    console.log('indexes ready:', INDEXES.length);

    const columns = await query(
        `SELECT column_name, data_type, is_nullable, column_default
         FROM information_schema.columns
         WHERE table_schema = 'public' AND table_name = 'users'
         ORDER BY ordinal_position`
    );
    console.log('users columns:');
    columns.rows.forEach(column => {
        console.log(`  ${column.column_name.padEnd(16)} ${column.data_type.padEnd(28)} nullable=${column.is_nullable} default=${column.column_default || 'none'}`);
    });

    const created = await query(
        `SELECT table_name FROM information_schema.tables
         WHERE table_schema = 'public'
           AND table_name IN ('addresses','orders','order_items','customer_cart_items','customer_wishlist')
         ORDER BY table_name`
    );
    console.log('customer tables present:', created.rows.map(row => row.table_name).join(', '));

    await closeDb();
}

migrate().catch(async error => {
    console.error(`Customer schema migration failed: ${error.message}`);
    try { await closeDb(); } catch { /* already closed */ }
    process.exitCode = 1;
});